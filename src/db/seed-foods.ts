export async function seedFoodsIfNeeded() {
  try {
    const existing = await db.select({ total: count() }).from(foods);
    if (existing[0] && Number(existing[0].total) > 0) {
      return;
    }
    console.log('Seeding initial verified food database into PostgreSQL...');
    await db.insert(foods).values(INITIAL_FOOD_DATABASE);
    console.log(`Seeded ${INITIAL_FOOD_DATABASE.length} verified foods.`);
  } catch (error) {
    console.error('Failed to seed foods database:', error);
  }
}
